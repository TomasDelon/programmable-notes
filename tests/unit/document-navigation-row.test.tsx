import { fireEvent, render, screen } from '@testing-library/react';
import { FileText, Code2 } from 'lucide-react';
import { expect, it, vi } from 'vitest';
import type { DragEvent } from 'react';
import { DocumentNavigationRow } from '../../src/workspace/DocumentNavigationRow';

it('retains the exact ordinary document button, selected class, indentation, icon and accessible name', () => {
  const ui = render(
    <DocumentNavigationRow
      title="Notes & <source>"
      selected
      depth={2}
      icon={FileText}
      extraClass=" tree-dragged tree-drop-before"
      onOpen={vi.fn()}
      draggable
    />,
  );
  const button = screen.getByRole('button', { name: 'Open Notes & <source>' });
  expect(ui.container.children).toHaveLength(1);
  expect(ui.container.firstElementChild).toBe(button);
  expect(button).toHaveAttribute('type', 'button');
  expect(button.className).toBe(
    'nav-file selected tree-dragged tree-drop-before',
  );
  expect(button).toHaveAttribute('aria-current', 'page');
  expect(button).toHaveAttribute('title', 'Notes & <source>');
  expect(button).toHaveAttribute('draggable', 'true');
  expect(button.style.marginLeft).toBe('32px');
  expect(button.style.paddingLeft).toBe('7px');
  expect(button.style.width).toBe('calc(100% - 32px)');
  expect(
    [...button.children].map((child) => child.tagName.toLowerCase()),
  ).toEqual(['svg', 'span']);
  expect(button.children[0]).toHaveClass('lucide-file-text');
  expect(button.children[0]).toHaveAttribute('width', '14');
  expect(button.children[0]).toHaveAttribute('stroke-width', '1.65');
  expect(button.children[1]!.textContent).toBe('Notes & <source>');
});

it('keeps admission and selection host-owned, and leaves native button keyboard handling intact', () => {
  let admitted = false;
  const open = vi.fn(() => admitted);
  const ui = render(
    <DocumentNavigationRow
      title="Module"
      selected={false}
      icon={Code2}
      onOpen={open}
    />,
  );
  const button = screen.getByRole('button', { name: 'Open Module' });
  expect(button.className).toBe('nav-file ');
  expect(button).not.toHaveAttribute('aria-current');
  expect(button).toHaveAttribute('draggable', 'false');
  expect(button.style.marginLeft).toBe('0px');
  expect(button.children[0]).toHaveClass('lucide-code-xml');
  button.focus();
  expect(button).toHaveFocus();
  // jsdom does not synthesize a native key activation. Keep key defaults unhandled,
  // then deliver the zero-detail click generated by a browser keyboard activation.
  expect(fireEvent.keyDown(button, { key: 'Enter' })).toBe(true);
  expect(fireEvent.keyDown(button, { key: ' ' })).toBe(true);
  expect(open).not.toHaveBeenCalled();
  fireEvent.click(button, { detail: 0 });
  expect(open).toHaveBeenCalledOnce();
  expect(button).not.toHaveAttribute('aria-current');
  admitted = true;
  fireEvent.click(button, { detail: 1 });
  expect(open).toHaveBeenCalledTimes(2);
  expect(button).not.toHaveAttribute('aria-current');
  ui.rerender(
    <DocumentNavigationRow
      title="Module"
      selected
      icon={Code2}
      onOpen={open}
    />,
  );
  expect(screen.getByRole('button')).toBe(button);
  expect(button).toHaveAttribute('aria-current', 'page');
});

it('forwards each drag event unchanged so the existing host decides data transfer, cancellation and bubbling', () => {
  const seen: Array<[string, HTMLElement, unknown]> = [];
  const record = (name: string) =>
    vi.fn((event: DragEvent<HTMLButtonElement>) => {
      seen.push([name, event.currentTarget, event.dataTransfer]);
      if (name === 'over' || name === 'drop') {
        event.preventDefault();
        event.stopPropagation();
      }
    });
  const handlers = {
    onDragStart: record('start'),
    onDragEnd: record('end'),
    onDragOver: record('over'),
    onDrop: record('drop'),
    onDragLeave: record('leave'),
  };
  const bubbled = vi.fn();
  render(
    <div onDragOver={bubbled} onDrop={bubbled}>
      <DocumentNavigationRow
        title="Document"
        selected={false}
        icon={FileText}
        onOpen={vi.fn()}
        draggable
        {...handlers}
      />
    </div>,
  );
  const button = screen.getByRole('button');
  const dataTransfer = {
    effectAllowed: 'move',
    getData: vi.fn(),
    setData: vi.fn(),
  };
  fireEvent.dragStart(button, { dataTransfer });
  expect(fireEvent.dragOver(button, { dataTransfer })).toBe(false);
  expect(fireEvent.drop(button, { dataTransfer })).toBe(false);
  fireEvent.dragLeave(button, { dataTransfer, relatedTarget: button });
  fireEvent.dragEnd(button, { dataTransfer });
  expect(seen).toEqual(
    ['start', 'over', 'drop', 'leave', 'end'].map((name) => [
      name,
      button,
      dataTransfer,
    ]),
  );
  for (const handler of Object.values(handlers))
    expect(handler).toHaveBeenCalledOnce();
  expect(bubbled).not.toHaveBeenCalled();
  expect(dataTransfer.setData).not.toHaveBeenCalled();
});
